import { test } from 'node:test'
import assert from 'node:assert/strict'
import { JSDOM } from 'jsdom'
import { createServer } from 'vite'
import { createElement, act } from 'react'

test('rendered app routes drag events for boards, folder hierarchies, links and kubeconfig manual sorting', async () => {
  const dom = new JSDOM('<div id="root"></div>', { url: 'https://orbit-test.invalid/' })
  const saved = new Map()
  for (const [key, value] of Object.entries({ window: dom.window, document: dom.window.document, HTMLElement: dom.window.HTMLElement, Element: dom.window.Element, Node: dom.window.Node, navigator: dom.window.navigator, localStorage: dom.window.localStorage, IS_REACT_ACT_ENVIRONMENT: true })) {
    saved.set(key, Object.getOwnPropertyDescriptor(globalThis, key))
    Object.defineProperty(globalThis, key, { configurable: true, writable: true, value })
  }
  const server = await createServer({ configFile: false, logLevel: 'silent', server: { middlewareMode: true }, appType: 'custom' })
  let root
  try {
    const { default: App } = await server.ssrLoadModule('/src/App.tsx')
    const { createRoot } = await import('react-dom/client')
    root = createRoot(document.getElementById('root'))
    await act(() => root.render(createElement(App)))
    const button = (name) => {
      const result = [...document.querySelectorAll('button')].find((item) => item.getAttribute('aria-label') === name || item.textContent.trim() === name)
      assert.ok(result, `Missing button: ${name}`)
      return result
    }
    const click = async (element) => { await act(() => element.click()) }
    const drag = async (source, target, fraction = .5, beforeDrop) => {
      const transfer = { setData() {}, setDragImage() {}, effectAllowed: '', dropEffect: '' }
      const event = (type, current, y) => {
        const value = new dom.window.MouseEvent(type, { bubbles: true, cancelable: true, clientY: y, clientX: 100 })
        Object.defineProperty(value, 'dataTransfer', { value: transfer })
        return current.dispatchEvent(value)
      }
      const oldBounds = target.getBoundingClientRect
      target.getBoundingClientRect = () => ({ top: 100, bottom: 200, height: 100, left: 0, right: 200, width: 200 })
      await act(() => event('dragstart', source, 150))
      await act(() => event('dragover', target, 100 + fraction * 100))
      if (beforeDrop) beforeDrop()
      await act(() => event('drop', target, 100 + fraction * 100))
      await act(() => event('dragend', source, 150))
      target.getBoundingClientRect = oldBounds
      // Start a new interaction rather than a click generated by drag release.
      await new Promise((resolve) => setTimeout(resolve, 210))
    }
    const boardOrder = () => [...document.querySelectorAll('[data-board-id]')].map((item) => item.dataset.boardId)
    assert.deepEqual(boardOrder(), ['board-engineering', 'board-inspiration'])
    await drag(button('拖动看板 灵感收藏'), document.querySelector('[data-board-id="board-engineering"]'), .1, () => assert.ok(document.querySelector('.tree-item.drop-before')))
    assert.deepEqual(boardOrder(), ['board-inspiration', 'board-engineering'])
    // Sibling sorting, nesting, then promoting a subtree via a board drop.
    const learning = button('拖动分组 工程效率 / 学习资料')
    const tools = button('选择分组 工程效率 / 常用工具').closest('[data-group-id]')
    await drag(learning, tools, .1, () => assert.ok(tools.classList.contains('drop-before')))
    let engineering = [...document.querySelectorAll('.tree-item-wrap')].find((item) => item.querySelector('[data-board-id="board-engineering"]'))
    assert.equal(engineering.querySelector('[data-group-id]').querySelector('.folder-select span').textContent, '学习资料')
    await drag(button('拖动分组 工程效率 / 学习资料'), button('选择分组 工程效率 / Kubernetes').closest('[data-group-id]'), .5)
    assert.ok(button('选择分组 工程效率 / Kubernetes / 学习资料'))
    // A parent-to-descendant drop is rejected in the actual UI, not just the model.
    await drag(button('拖动分组 工程效率 / Kubernetes'), button('选择分组 工程效率 / Kubernetes / 学习资料').closest('[data-group-id]'), .5, () => assert.equal(document.querySelectorAll('.drop-inside, .drop-before, .drop-after').length, 0))
    assert.ok(button('选择分组 工程效率 / Kubernetes / 学习资料'))
    await drag(button('拖动分组 工程效率 / Kubernetes'), document.querySelector('[data-board-id="board-inspiration"]'), .5)
    assert.ok(button('选择分组 灵感收藏 / Kubernetes / 学习资料'))
    await click(button('选择分组 工程效率 / 常用工具'))
    const linkTitles = () => [...document.querySelectorAll('.link-inline-title')].map((item) => item.value)
    const opened = []
    dom.window.open = (...args) => { opened.push(args); return null }
    await click(button('打开 Google'))
    assert.equal(opened.length, 1, 'the large open area must open exactly once')
    assert.equal(opened[0][0], 'https://www.google.com/')
    for (const input of document.querySelectorAll('[data-link-id="link-google"] input')) await click(input)
    assert.equal(opened.length, 1, 'inline edits must not open the browser')
    await drag(button('拖动链接 JSON 转 YAML'), document.querySelector('[data-link-id="link-google"]'), .1)
    assert.deepEqual(linkTitles(), ['JSON 转 YAML', 'Google', 'OneTab'])
    // Inline editing must not initiate a drag.
    const titleInput = document.querySelector('.link-inline-title')
    await drag(titleInput, document.querySelector('[data-link-id="link-google"]'), .5, () => assert.equal(document.querySelectorAll('.drag-preview').length, 0))
    assert.deepEqual(linkTitles(), ['JSON 转 YAML', 'Google', 'OneTab'])
    await drag(button('拖动链接 OneTab'), document.querySelector('[data-board-id="board-inspiration"]'), .5)
    assert.ok(button('选择分组 灵感收藏 / 未分组'))
    assert.deepEqual(linkTitles(), ['OneTab'])
    await click(button('Kubeconfig'))
    const configIds = () => [...document.querySelectorAll('[data-config-id]')].map((item) => item.dataset.configId)
    const originalConfigs = configIds()
    await drag(button('拖动环境分组 实验环境'), document.querySelector('[data-kube-group-id]'), .1)
    assert.equal(document.querySelector('[data-kube-group-id] .group-icon + span').textContent, '实验环境')
    const sorting = document.querySelector('select[aria-label="配置排序"]')
    await act(() => { sorting.value = 'name'; sorting.dispatchEvent(new dom.window.Event('change', { bubbles: true })) })
    const displayed = configIds()
    const sourceId = displayed.at(-1)
    const source = document.querySelector(`[data-config-id="${sourceId}"] [data-drag-handle]`)
    await drag(source, document.querySelector(`[data-config-id="${displayed[0]}"]`), .1)
    assert.equal(sorting.value, 'manual')
    assert.equal(configIds()[0], sourceId)
    assert.equal(configIds().length, originalConfigs.length)
    const group = document.querySelector('[data-kube-group-id]')
    await drag(document.querySelector(`[data-config-id="${sourceId}"] [data-drag-handle]`), group, .5)
    assert.ok(configIds().includes(sourceId))
    assert.equal(document.querySelectorAll('.drag-preview').length, 0)
    const stored = JSON.parse(localStorage.getItem('orbit-boards'))
    assert.equal(stored[0].id, 'board-inspiration')
    assert.equal(stored.find((item) => item.id === 'board-inspiration').groups.some((item) => item.name === '学习资料'), true)
    await act(() => root.unmount())
    root = createRoot(document.getElementById('root'))
    await act(() => root.render(createElement(App)))
    await click(button('书签看板'))
    assert.deepEqual(boardOrder(), ['board-inspiration', 'board-engineering'])
    assert.ok(button('选择分组 灵感收藏 / Kubernetes / 学习资料'))
    await click(button('选择分组 工程效率 / 常用工具'))
    assert.deepEqual(linkTitles(), ['JSON 转 YAML', 'Google'])
    await click(button('Kubeconfig'))
    assert.equal(document.querySelector('select[aria-label="配置排序"]').value, 'manual')
  } finally {
    if (root) await act(() => root.unmount())
    await server.close()
    dom.window.close()
    for (const [key, descriptor] of saved) {
      if (descriptor) Object.defineProperty(globalThis, key, descriptor)
      else delete globalThis[key]
    }
  }
})
